!!"false" == !!"true";
// ! - інвертує вираз, відповідно, !! - це подвійна інверсія.
// !!'false' містить непорожній рядок, відповідно, 'false' переводиться в булеве true
// перша інверсія інвертує true в false, друга інверсія інвертує false в true: !'false' = false
// друга інверсія перетворює false в true, тож !!'false' = true
// за аналогією отримуємо !!'true' = true
// true == true -> result = true

0 || '0' && 1
// && має вищий пріоритет, тож обчислюється першим. непорожній рядок '0' отримує значення true
// true && 1 = true && true - повертається останнє true, тобто 1
// 0 || 1 = false || true. || повертає перше значення, якщо воно true, і друге значення, якщо перше дорівнює false
// у даному виразі перше значення дорівнює false, тож повертається друге - 1. result = 1

(+null == false) < 1;
