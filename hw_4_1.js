"10" - 5 === 6;
// '10' приводиться до типу Number.
// Після перетворення вираз має вигляд: 10 - 5 === 6;
// 5 === 6 - строге порівняння перевіряє чи дорівнює значення праворуч значенню ліворуч
// та чи до однакового типу даних належать змінні.
// хоча тип даних 5 і 6 - це Number, але значення 5 не дорівнює значенню 6. result = false

true + false;
// вираз виконує операцію арифметичного додавання.
// булеві значення true і false відповідають значенням 1 і 0 типу Number
// після перетворення вираз має вигляд: 1 + 0 -> result = 1

"4px" - 3;
